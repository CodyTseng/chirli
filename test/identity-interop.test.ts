function simulated(current: () => Event[] | Promise<Event[]>) {
	const published: Event[] = [],
		filters: Filter[] = [];
	let subscriptions = 0;
	const transport: Transport = {
		query: async (_relays, filter) => {
			filters.push(filter);
			return current();
		},
		publish: async (_relays, event) => {
			published.push(event);
		},
		close() {},
		subscribe: (_relays, filter, receive) => {
			filters.push(filter);
			if (filter.kinds?.includes(1059)) subscriptions++;
			return {
				ready: Promise.resolve()
					.then(current)
					.then((events) => {
						for (const event of events)
							if (matchFilter(filter, event)) receive(event, "history");
					}),
				close() {},
			};
		},
	};
	return {
		transport,
		published,
		filters,
		get subscriptions() {
			return subscriptions;
		},
	};
}
