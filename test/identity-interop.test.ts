for (const kind of ["local", "nsec", "bunker"] as const) {
	test(`${kind}: nip17 identity-key service exchanges live commands/replies with a separate-key peer`, async () => {
		const remote = kind === "bunker" ? await mockBunker() : undefined,
			relay = remote ? undefined : await testRelay(),
			url = remote?.relay ?? relay?.url;
		assert.ok(url);
		const signer = remote
			? bunkerSigner(remote.uri, {
					clientSecret: generateSecretKey(),
					timeoutMs: 1000,
				})
			: kind === "nsec"
				? nsecSigner(nsecEncode(generateSecretKey()))
				: undefined;
		const identity = signer
				? await identityFromSigner(signer, { mode: "nip17" })
				: localNip17Identity(),
			peerIdentity = localIdentity();
		const wire = new WebSocketTransport(5000, (t) => identity.sign(t)),
			events: Event[] = [];
		const transport: Transport = {
			query: wire.query.bind(wire),
			subscribe: wire.subscribe.bind(wire),
			close: () => wire.close(),
			publish: async (relays, event) => {
				events.push(event);
				await wire.publish(relays, event);
			},
		};
		const service = new Client({
				mode: "nip17",
				identity,
				relays: [url],
				transport,
				database: ":memory:",
				storageKey: generateSecretKey(),
			}),
			peer = new Client({
				mode: "nip4e",
				identity: peerIdentity,
				relays: [url],
				database: ":memory:",
				storageKey: generateSecretKey(),
			});
		const bot = new Bot(service);
		let commands = 0,
			response = "";
		bot.command(
			{
				command: "ping",
				title: "ping",
				description: "Run /ping in a private message.",
				scopes: ["kind:14"],
				args: z.object({
					text: z
						.string()
						.optional()
						.meta({ label: "Text", nipcdType: "text" }),
				}),
			},
			async (ctx) => {
				commands++;
				await ctx.reply("identity-key pong");
			},
		);
		peer.handle((message) => {
			response = message.text;
		});
		try {
			await service.announce();
			await peer.announce();
			await wire.publish([url], await list(peerIdentity, url));
			const claim = events.find((event) => event.kind === 10044);
			assert.ok(claim);
			assert.equal(claim.pubkey, identity.pubkey);
			assert.deepEqual(claim.tags, [["n", identity.pubkey]]);
			assert.ok(verifyEvent(claim));
			if (remote) {
				assert.equal(claim.pubkey, remote.accountPubkey);
				assert.notEqual(claim.pubkey, remote.transportPubkey);
				assert.equal(identity.encryptionKey, undefined);
			}
			await service.announce();
			assert.equal(
				new Set(
					events
						.filter((event) => event.kind === 10044)
						.map((event) => event.id),
				).size,
				1,
				"a matching announcement is reused",
			);
			await bot.start();
			await peer.start();
			await peer.send(identity.pubkey, "/ping");
			await until(() => response !== "");
			await service.idle();
			await peer.idle();
			assert.equal(response, "identity-key pong");
			assert.equal(commands, 1);
			const outgoing = events.find(
				(event) =>
					event.kind === 1059 &&
					event.tags.some(
						(tag) => tag[0] === "p" && tag[1] === peerIdentity.pubkey,
					),
			);
			assert.ok(outgoing);
			const decoded = unwrap(outgoing, peerIdentity);
			assert.ok(decoded);
			assert.deepEqual(decoded.seal.tags, [["n", identity.pubkey]]);
			assert.equal(decoded.seal.created_at, decoded.rumor.created_at);
			await bot.stop();
			await bot.start();
			await service.idle();
			assert.equal(commands, 1, "history/restart does not replay commands");
		} finally {
			await peer.close();
			await bot.client.close();
			bot.dispose();
			await signer?.close();
			if (remote) await remote.close();
			else {
				assert.ok(relay);
				await relay.close();
			}
		}
	});
}

